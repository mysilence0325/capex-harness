/**
 * Regenerate the precomputed `color-mix()` tokens.
 *
 * Run after changing component styles or the palette:
 * `pnpm exec tsx scripts/compat/generate-mix-tokens.ts`
 *
 * Writes two checked-in artifacts: the expression table the client bundler
 * rewrites with, and the stylesheet that rebinds the dark palette.
 * @module scripts/compat/generate-mix-tokens
 */
import { readFileSync, readdirSync, writeFileSync, statSync } from 'node:fs'
import { join, relative, resolve, sep } from 'node:path'
import { fileURLToPath } from 'node:url'
import {
  evaluateColorMix, findColorMix, formatColor, normalizeColorMix, readDeclarations, readRules, resolveVariables, tokenNameFor,
} from './color-mix.ts'

const ROOT = resolve(fileURLToPath(new URL('../..', import.meta.url)))
const PLATFORM = join(ROOT, 'packages/client/ui-theme/src/styles/design-platform.css')
const OUTPUT_CSS = join(ROOT, 'packages/client/ui-theme/src/styles/mix-fallbacks.css')
const OUTPUT_MAP = join(ROOT, 'scripts/compat/mix-token-map.json')

function stylesheets(): string[] {
  const files: string[] = []
  const walk = (directory: string): void => {
    for (const entry of readdirSync(directory, { withFileTypes: true })) {
      if (entry.name === 'node_modules' || entry.name === 'lib' || entry.name === 'dist') continue
      const path = join(directory, entry.name)
      if (entry.isDirectory()) walk(path)
      else if (entry.isFile() && entry.name.endsWith('.css')) files.push(path)
    }
  }
  for (const group of ['client', 'experimental']) {
    const base = join(ROOT, 'packages', group)
    try {
      if (statSync(base).isDirectory()) walk(base)
    } catch {
      // A group without packages is not an error for this generator.
    }
  }
  walk(join(ROOT, 'apps/web/src'))
  return files
}

const platform = readFileSync(PLATFORM, 'utf8')
const lightDeclarations = new Map(readRules(platform, 'body').flatMap(body => [...readDeclarations(body)]))
const darkDeclarations = new Map(readRules(platform, 'body[data-ds-dark-theme]').flatMap(body => [...readDeclarations(body)]))
// Theme sheets outside the palette also contribute mix operands (onboarding).
for (const extra of ['onboarding.css', 'gradient-shadow-text.css']) {
  const css = readFileSync(join(ROOT, 'packages/client/ui-theme/src/styles', extra), 'utf8')
  for (const [name, value] of readDeclarations(readRules(css, 'body')[0] ?? '')) lightDeclarations.set(name, value)
}
// The dark rule only restates what changes, so it inherits the light palette.
const light = new Map([...lightDeclarations].map(([name, value]) => [name, resolveVariables(value, lightDeclarations)]))
const merged = new Map([...lightDeclarations, ...darkDeclarations])
const dark = new Map([...merged].map(([name, value]) => [name, resolveVariables(value, merged)]))

const expressions = new Set<string>()
for (const file of stylesheets()) {
  const css = readFileSync(file, 'utf8')
  for (const expression of findColorMix(css)) expressions.add(normalizeColorMix(expression))
}

interface Entry {
  readonly expression: string
  readonly token: string
  readonly lightValue: string
  readonly darkValue: string
}

const entries: Entry[] = []
for (const expression of [...expressions].sort()) {
  const lightColor = evaluateColorMix(expression, light)
  const darkColor = evaluateColorMix(expression, dark)
  const resolved = lightColor ?? darkColor
  if (resolved === undefined) continue
  const lightValue = formatColor(lightColor ?? resolved)
  const darkValue = formatColor(darkColor ?? resolved)
  entries.push({ expression, token: tokenNameFor(expression), lightValue, darkValue })
}

const lightRule = entries.map(entry => `  ${entry.token}: ${entry.lightValue};`).join('\n')
const darkRule = entries.filter(entry => entry.lightValue !== entry.darkValue)
  .map(entry => `  ${entry.token}: ${entry.darkValue};`).join('\n')

const css = [
  '/* Generated by scripts/compat/generate-mix-tokens.ts. Do not edit by hand.',
  ' * Precomputed color-mix() results so Chromium 102 keeps every tint. */',
  'body {',
  lightRule,
  '}',
  '',
  'body[data-ds-dark-theme] {',
  darkRule,
  '}',
  '',
].join('\n')
writeFileSync(OUTPUT_CSS, css)

// A JSON table keeps the bundler config free of TypeScript imports: tsdown
// loads configs through Node's native type stripping, which rejects some files.
const map = Object.fromEntries(entries.map(entry => [entry.expression, { token: entry.token, fallback: entry.lightValue }]))
writeFileSync(OUTPUT_MAP, `${JSON.stringify(map, null, 2)}\n`)

process.stdout.write(`mix tokens: ${String(entries.length)} expressions, `
  + `${String(entries.filter(entry => entry.lightValue !== entry.darkValue).length)} theme-dependent\n`)
process.stdout.write(`wrote ${relative(ROOT, OUTPUT_CSS).split(sep).join('/')} and ${relative(ROOT, OUTPUT_MAP).split(sep).join('/')}\n`)
